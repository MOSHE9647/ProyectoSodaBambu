<?php

namespace App\Models;

use App\Contracts\Receipable;
use App\Enums\ContractState;
use Carbon\Carbon;
use Database\Factories\ContractFactory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\Relations\MorphMany;
use Illuminate\Database\Eloquent\SoftDeletes;

class Contract extends Model implements Receipable
{
    /** @use HasFactory<ContractFactory> */
    use HasFactory, SoftDeletes;

    /**
     * The attributes that are mass assignable.
     *
     * @var list<string>
     */
    protected $fillable = [
        'user_id',
        'client_id',
        'business_name',
        'start_date',
        'end_date',
        'days_to_serve',
        'portions_per_day',
        'total_value',
    ];

    /**
     * The attributes that should be cast.
     *
     * @var array<string, string>
     */
    protected $casts = [
        'start_date' => 'date',
        'end_date' => 'date',
        'days_to_serve' => 'array',
        'portions_per_day' => 'integer',
        'total_value' => 'integer',
    ];

    /**
     * Accesor for dynamic contract status based on dates and deletion state.
     *
     * @return string Contract status: 'upcoming', 'active', 'expired', or 'inactive'
     */
    public function getStatusAttribute(): string
    {
        if ($this->deleted_at) {
            return ContractState::INACTIVE->value;
        }
        $today = now()->startOfDay();
        if ($today->lt($this->start_date)) {
            return ContractState::UPCOMING->value;
        }
        if ($today->gt($this->end_date)) {
            return ContractState::EXPIRED->value;
        }

        return ContractState::ACTIVE->value;
    }

    /**
     * Get the contract period as a formatted date range.
     *
     * @return string Formatted period or 'Undefined' when dates are missing.
     */
    public function getPeriodAttribute(): string
    {
        if ($this->start_date && $this->end_date) {
            $start = $this->start_date->locale('es')->isoFormat('D MMM YYYY');
            $end = $this->end_date->locale('es')->isoFormat('D MMM YYYY');

            return "$start - $end";
        }

        return 'No definido';
    }

    /**
     * Relation: Generated by User.
     * A contract belongs to a single user who processed it.
     *
     * @return BelongsTo<User, Contract>
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /**
     * Relation: Associated Client.
     * A contract belongs to a single client.
     *
     * @return BelongsTo<Client, Contract>
     */
    public function client(): BelongsTo
    {
        return $this->belongsTo(Client::class);
    }

    /**
     * Relation: Contract Details.
     * A contract can have multiple details (products, meal times, etc.).
     *
     * @return HasMany<ContractDetail>
     */
    public function details()
    {
        return $this->hasMany(ContractDetail::class);
    }

    /**
     * Relation: Payments.
     * A contract can have multiple payments (e.g., split payments).
     *
     * @return MorphMany<Payment>
     */
    public function payments(): MorphMany
    {
        return $this->morphMany(Payment::class, 'origin');
    }

    // ===== Receipable Interface Implementation =====

    /**
     * Get the receipt/invoice number for this contract.
     */
    public function getReceiptNumber(): string
    {
        return "CONTRATO-{$this->id}";
    }

    /**
     * Get the date when this contract was created (for receipt purposes).
     */
    public function getReceiptDate(): Carbon
    {
        return $this->created_at ?? now();
    }

    /**
     * Get the total value of this contract.
     */
    public function getReceiptTotal(): int
    {
        return $this->total_value ?? 0;
    }

    /**
     * Get the contract details as receipt items.
     */
    public function getReceiptItems(): array
    {
        return $this->details->map(function ($detail) {
            return [
                'name' => $detail->product?->name ?? "Producto #{$detail->product_id}",
                'quantity' => $detail->quantity ?? 1,
                'unit_price' => $detail->unit_price ?? 0,
                'sub_total' => $detail->subtotal ?? 0,
                'applied_tax' => $detail->applied_tax ?? 0,
            ];
        })->toArray();
    }

    /**
     * Get the contract subtotal (sum of all details before tax).
     */
    public function getReceiptSubtotal(): int
    {
        return $this->details->sum('subtotal') ?? 0;
    }

    /**
     * Get the total tax amount for all contract details.
     */
    public function getReceiptTaxTotal(): int
    {
        return collect($this->getReceiptItems())->reduce(function ($carry, $item) {
            $taxAmount = (int) round($item['sub_total'] * ($item['applied_tax'] / 100));

            return $carry + $taxAmount;
        }, 0);
    }

    /**
     * Get the receipt type label.
     */
    public function getReceiptType(): string
    {
        return 'Comprobante de contrato';
    }

    /**
     * Check if this contract can generate a receipt.
     */
    public function canGenerateReceipt(): bool
    {
        return $this->id && $this->total_value > 0 && $this->details->count() > 0;
    }
}
